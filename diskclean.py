def build_suggestions(scan):
    out = {}

    def size_of(path):
        node, _ = scan.find(path)
        if node is not None:
            return node.size
        if not os.path.exists(path):
            return None
        try:
            r = subprocess.run(["du", "-sk", path], capture_output=True, text=True, timeout=120)
            return int(r.stdout.split()[0]) * 1024
        except Exception:
            return None

    def add(path, size, title, safety, why, action="delete", command=None):
        if size is None or size < MIN_SUGGEST:
            return
        if action == "delete" and not is_deletable(path)[0]:
            return
        out[path] = {"path": path, "size": size, "title": title, "safety": safety, "why": why,
                     "action": action, "command": command}

    for path, (kind, size) in scan.candidates.items():
        title, safety, why = KIND_INFO[kind]
        add(path, size, title, safety, why)

    in_root = lambda p: p == scan.root or p.startswith(scan.root.rstrip(os.sep) + os.sep)
    for path, title, safety, why, action, command in KNOWN_LOCATIONS:
        if in_root(path) and path not in out:
            add(path, size_of(path), title, safety, why, action, command)

    for parent, title, safety, why in PER_CHILD:
        if not in_root(parent):
            continue
        node, _ = scan.find(parent)
        if node is None:
            continue
        for d in node.dirs:
            if d.path not in out:
                add(d.path, d.size, f"{title}: {d.name}", safety, why)

    # Drop suggestions nested inside another suggestion.
    paths = sorted(out)
    result = []
    for p in paths:
        if any(p.startswith(q + os.sep) for q in paths if q != p):
            continue
        result.append(out[p])
    result.sort(key=lambda s: s["size"], reverse=True)
    return result


