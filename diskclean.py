TOKEN = secrets.token_urlsafe(24)

MIN_KEEP_DIR = 1_000_000      # dirs smaller than this are folded into "smaller items"
MAX_KEEP_DIRS = 300
MIN_KEEP_FILE = 500_000
MAX_KEEP_FILES = 200
MIN_SUGGEST = 50_000_000      # don't bother suggesting anything below 50 MB

sys.setrecursionlimit(20000)


# --------------------------------------------------------------------------- scanning

class DirNode:
    __slots__ = ("name", "path", "size", "nfiles", "dirs", "files", "other_size", "other_count")

    def __init__(self, name, path):
        self.name = name
        self.path = path
        self.size = 0
        self.nfiles = 0
        self.dirs = []          # list[DirNode], largest first
        self.files = []         # list[(name, size)], largest first
        self.other_size = 0     # bytes in folded-away small items
        self.other_count = 0


def disk_bytes(st):
    # Allocated blocks, not apparent size: sparse files (Docker.raw) report terabytes otherwise.
    return st.st_blocks * 512


def classify(name, siblings, parent):
    """Return a candidate kind for a regenerable folder, or None."""
    if name == "node_modules":
        return "node_modules"
    if name == ".next":
        return "next"
    if name in (".nuxt", ".svelte-kit", ".turbo", ".parcel-cache", ".angular", ".expo", ".vercel"):
        return "frontend_cache"
    if name == ".dart_tool":
        return "dart_tool"
    if name == "build" and siblings & {"pubspec.yaml", "build.gradle", "build.gradle.kts", "settings.gradle", "settings.gradle.kts"}:
        return "build_output"
    if name == "Pods" and "Podfile" in siblings:
        return "pods"
    if name == "target" and "Cargo.toml" in siblings:
        return "rust_target"
    if name == "DerivedData":
        return "derived_data"
    if name == ".gradle" and parent != HOME and siblings & {"build.gradle", "build.gradle.kts", "settings.gradle", "settings.gradle.kts", "gradlew"}:
        return "gradle_project"
    if name in ("venv", ".venv"):
        return "venv"
    if name == "worktrees" and os.path.basename(parent) in (".claude", ".worktrees"):
        return "worktrees"
    return None


