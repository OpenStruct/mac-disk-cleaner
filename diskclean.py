def is_deletable(path):
    """(ok, reason). Only paths strictly inside the home folder, never core folders."""
    if not isinstance(path, str) or not path or "\0" in path:
        return False, "invalid path"
    p = os.path.normpath(os.path.abspath(path))
    if p != path.rstrip(os.sep):
        return False, "path must be absolute and normalised"
    parent_real = os.path.realpath(os.path.dirname(p))
    home_real = os.path.realpath(HOME)
    if not (parent_real == home_real or parent_real.startswith(home_real + os.sep)):
        return False, "only items inside your home folder can be removed"
    if p in PROTECTED or os.path.join(parent_real, os.path.basename(p)) in PROTECTED:
        return False, "this is a core folder; remove items inside it instead"
    for bad in NEVER_INSIDE:
        if p == bad or p.startswith(bad + os.sep):
            return False, "protected location (keychains, iCloud, Docker data, mail, photos…)"
    if os.path.basename(p) == ".git":
        return False, "refusing to delete git history"
    if not os.path.lexists(p):
        return False, "no longer exists"
    return True, ""


def move_to_trash(path):
    trash = H(".Trash")
    base = os.path.basename(path)
    dest = os.path.join(trash, base)
    if os.path.lexists(dest):
        dest = os.path.join(trash, f"{base} {time.strftime('%H.%M.%S')}-{secrets.token_hex(2)}")
    try:
        os.rename(path, dest)
        return
    except OSError:
        pass
    # Fallback through Finder (path passed as argv, never interpolated into the script).
    r = subprocess.run(["osascript", "-e", "on run argv", "-e",
                        'tell application "Finder" to delete (POSIX file (item 1 of argv) as alias)',
                        "-e", "end run", path], capture_output=True, text=True, timeout=120)
    if r.returncode != 0:
        raise OSError(r.stderr.strip() or "Finder could not move the item to the Trash")


def delete_forever(path):
    if os.path.isdir(path) and not os.path.islink(path):
        def onerror(func, p, exc):
            try:
                os.chmod(p, 0o700)
                func(p)
            except OSError:
                pass
        shutil.rmtree(path, onerror=onerror)
        if os.path.exists(path):
            raise OSError("some files could not be removed (permissions)")
    else:
        os.remove(path)


def empty_trash():
    r = subprocess.run(["osascript", "-e", 'tell application "Finder" to empty trash'],
                       capture_output=True, text=True, timeout=600)
    if r.returncode == 0:
        return
    trash = H(".Trash")
    for e in os.scandir(trash):
        delete_forever(e.path)


def disk_info():
    st = os.statvfs(HOME)
    total = st.f_blocks * st.f_frsize
    free = st.f_bavail * st.f_frsize
    return {"total": total, "free": free, "used": total - free}


# --------------------------------------------------------------------------- HTTP

STATE = {"scan": None, "suggestions": None, "busy": False}
STATE_LOCK = threading.Lock()


def start_scan(root):
    scan = Scan(root)
    STATE["scan"] = scan
    STATE["suggestions"] = None

    def work():
        scan.run()
        STATE["suggestions"] = build_suggestions(scan)
    threading.Thread(target=work, daemon=True).start()


class Handler(BaseHTTPRequestHandler):
    def log_message(self, *a):
        pass

    def send_json(self, obj, code=200):
        body = json.dumps(obj).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)

    STATIC_TYPES = {".woff2": "font/woff2", ".svg": "image/svg+xml", ".png": "image/png"}

    def send_static(self, name):
        path = HERE / "static" / name
        ctype = self.STATIC_TYPES.get(path.suffix)
        if "/" in name or name.startswith(".") or ctype is None or not path.is_file():
            return self.send_json({"error": "not found"}, 404)
        body = path.read_bytes()
        self.send_response(200)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "max-age=86400")
        self.end_headers()
        self.wfile.write(body)

    def host_ok(self):
        host = (self.headers.get("Host") or "").split(":")[0]
        return host in ("127.0.0.1", "localhost")

    def do_GET(self):
        if not self.host_ok():
            return self.send_json({"error": "bad host"}, 403)
        u = urlparse(self.path)
        q = {k: v[0] for k, v in parse_qs(u.query).items()}
        if u.path == "/":
            html = ((HERE / "index.html").read_text().replace("__TOKEN__", TOKEN)
                    .replace("__HOME__", json.dumps(HOME)).replace("__VERSION__", __version__))
            body = html.encode()
            self.send_response(200)
            self.send_header("Content-Type", "text/html; charset=utf-8")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)
            return
        if u.path.startswith("/static/"):
            return self.send_static(u.path[len("/static/"):])
        if self.headers.get("X-Token") != TOKEN:
            return self.send_json({"error": "bad token"}, 403)
        scan = STATE["scan"]
        if u.path == "/api/status":
            s = None
            if scan:
                s = {"root": scan.root, "files": scan.files, "dirs": scan.dirs, "bytes": scan.bytes,
                     "errors": scan.errors, "current": scan.current, "done": STATE["suggestions"] is not None,
                     "elapsed": (scan.finished or time.time()) - scan.started}
            return self.send_json({"scan": s, "disk": disk_info()})
        if not scan or STATE["suggestions"] is None:
            return self.send_json({"error": "no finished scan"}, 409)
        if u.path == "/api/node":
            node, _ = scan.find(q.get("path", scan.root))
            if node is None:
                return self.send_json({"error": "folder not in scan (too small or removed)"}, 404)
            flagged = frozenset(s["path"] for s in STATE["suggestions"] if s["safety"] == "safe")
            return self.send_json(node_json(node, flagged))
        if u.path == "/api/largest":
            return self.send_json(largest_files(scan.tree))
        if u.path == "/api/suggestions":
            return self.send_json(STATE["suggestions"])
        self.send_json({"error": "not found"}, 404)

    def do_POST(self):
        if not self.host_ok() or self.headers.get("X-Token") != TOKEN:
            return self.send_json({"error": "forbidden"}, 403)
        try:
            n = int(self.headers.get("Content-Length") or 0)
            data = json.loads(self.rfile.read(n) or b"{}")
        except ValueError:
            return self.send_json({"error": "bad json"}, 400)
        u = urlparse(self.path)

        if u.path == "/api/scan":
            root = os.path.normpath(os.path.expanduser(data.get("root") or HOME))
            if not os.path.isdir(root):
                return self.send_json({"error": f"not a folder: {root}"}, 400)
            scan = STATE["scan"]
            if scan and STATE["suggestions"] is None:
                return self.send_json({"error": "a scan is already running"}, 409)
            start_scan(root)
            return self.send_json({"ok": True})

        if u.path == "/api/reveal":
            path = data.get("path", "")
            if os.path.lexists(path):
                subprocess.run(["open", "-R", path])
            return self.send_json({"ok": True})

        if u.path == "/api/empty-trash":
            before = disk_info()["free"]
            try:
                empty_trash()
            except OSError as e:
                return self.send_json({"error": str(e)}, 500)
            scan = STATE["scan"]
            if scan and STATE["suggestions"] is not None:
                STATE["suggestions"] = [s for s in STATE["suggestions"] if s["action"] != "empty_trash"]
            return self.send_json({"ok": True, "freed": disk_info()["free"] - before})

        if u.path == "/api/remove":
            mode = data.get("mode")
            paths = data.get("paths") or []
            if mode not in ("trash", "delete") or not isinstance(paths, list):
                return self.send_json({"error": "bad request"}, 400)
            scan = STATE["scan"]
            if not scan or STATE["suggestions"] is None:
                return self.send_json({"error": "wait for the scan to finish"}, 409)
            with STATE_LOCK:
                results = []
                for path in paths:
                    ok, why = is_deletable(path)
                    if not ok:
                        results.append({"path": path, "ok": False, "error": why})
                        continue
                    size = self.known_size(scan, path)
                    try:
                        (move_to_trash if mode == "trash" else delete_forever)(path)
                    except OSError as e:
                        results.append({"path": path, "ok": False, "error": str(e)})
                        continue
                    scan.remove(path, size)
                    STATE["suggestions"] = [s for s in STATE["suggestions"]
                                            if s["path"] != path and not s["path"].startswith(path + os.sep)]
                    results.append({"path": path, "ok": True, "size": size})
            return self.send_json({"results": results, "disk": disk_info()})

        self.send_json({"error": "not found"}, 404)

    @staticmethod
    def known_size(scan, path):
        node, _ = scan.find(path)
        if node is not None:
            return node.size
        parent, _ = scan.find(os.path.dirname(path))
        if parent is not None:
            for name, s in parent.files:
                if name == os.path.basename(path):
                    return s
        if path in scan.candidates:
            return scan.candidates[path][1]
        for s in STATE["suggestions"] or []:
            if s["path"] == path:
                return s["size"]
        return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--version", action="version", version=f"Mac Disk Cleaner {__version__}")
    ap.add_argument("--port", type=int, default=8765)
    ap.add_argument("--no-open", action="store_true", help="don't open the browser")
    ap.add_argument("--no-scan", action="store_true", help="don't start scanning your home folder on launch")
    args = ap.parse_args()

    srv = ThreadingHTTPServer(("127.0.0.1", args.port), Handler)
    url = f"http://127.0.0.1:{args.port}/"
    print(f"Mac Disk Cleaner {__version__} running at {url}  (Ctrl+C to stop)")
    if not args.no_scan:
        start_scan(HOME)
    if not args.no_open:
        subprocess.Popen(["open", url])
    try:
        srv.serve_forever()
    except KeyboardInterrupt:
        print("\nbye")


if __name__ == "__main__":
    main()
