class Scan:
    def __init__(self, root):
        self.root = root
        self.files = 0
        self.dirs = 0
        self.bytes = 0
        self.errors = 0
        self.current = ""
        self.started = time.time()
        self.finished = None
        self.tree = None
        self.candidates = {}    # path -> (kind, size)
        self.seen_inodes = set()
        self.lock = threading.Lock()

    def scan_dir(self, path, name, dev, in_candidate, depth=0, pools=None):
        node = DirNode(name, path)
        self.dirs += 1
        self.current = path
        try:
            with os.scandir(path) as it:
                entries = list(it)
        except OSError:
            self.errors += 1
            return node

        siblings = {e.name for e in entries}
        sub_jobs = []   # (entry, kind)
        files = []
        for e in entries:
            try:
                st = e.stat(follow_symlinks=False)
            except OSError:
                self.errors += 1
                continue
            if e.is_dir(follow_symlinks=False):
                if st.st_dev != dev:
                    continue    # another volume mounted inside the tree
                kind = None if in_candidate else classify(e.name, siblings, path)
                sub_jobs.append((e, kind))
            else:
                if st.st_nlink > 1 and not e.is_symlink():
                    key = (st.st_dev, st.st_ino)
                    if key in self.seen_inodes:
                        continue
                    self.seen_inodes.add(key)
                sz = disk_bytes(st)
                files.append((e.name, sz))
                self.files += 1
                self.bytes += sz

        def run(job):
            e, kind = job
            child = self.scan_dir(e.path, e.name, dev, in_candidate or kind is not None, depth + 1, pools)
            if kind:
                with self.lock:
                    self.candidates[e.path] = (kind, child.size)
            return child

        if pools and depth < len(pools):
            children = list(pools[depth].map(run, sub_jobs))
        else:
            children = [run(j) for j in sub_jobs]

        node.size = sum(sz for _, sz in files) + sum(c.size for c in children)
        node.nfiles = len(files) + sum(c.nfiles for c in children)

        children.sort(key=lambda c: c.size, reverse=True)
        keep = [c for c in children[:MAX_KEEP_DIRS] if c.size >= MIN_KEEP_DIR]
        files.sort(key=lambda f: f[1], reverse=True)
        keep_files = [f for f in files[:MAX_KEEP_FILES] if f[1] >= MIN_KEEP_FILE]
        node.dirs = keep
        node.files = keep_files
        node.other_size = node.size - sum(c.size for c in keep) - sum(f[1] for f in keep_files)
        node.other_count = (len(children) - len(keep)) + (len(files) - len(keep_files))
        return node

    def run(self):
        try:
            dev = os.stat(self.root).st_dev
            # Two pools so a waiting parent never starves its own children (no deadlock).
            with ThreadPoolExecutor(16) as p1, ThreadPoolExecutor(8) as p2:
                self.tree = self.scan_dir(self.root, os.path.basename(self.root) or self.root, dev, False, 0, [p1, p2])
        finally:
            self.seen_inodes = set()
            self.finished = time.time()

    # ---- tree helpers

    def find(self, path):
        """Return (node, ancestors) for a directory path kept in the tree, or (None, ancestors)."""
        if self.tree is None:
            return None, []
        rel = os.path.relpath(path, self.root)
        if rel.startswith(".."):
            return None, []
        node, chain = self.tree, []
        if rel == ".":
            return node, chain
        for part in rel.split(os.sep):
            chain.append(node)
            nxt = next((d for d in node.dirs if d.name == part), None)
            if nxt is None:
                return None, chain
            node = nxt
        return node, chain

    def remove(self, path, size):
        """Reflect a deletion in the tree: subtract size up the chain and drop the entry."""
        parent_path, name = os.path.split(path)
        parent, chain = self.find(parent_path)
        for anc in chain:
            anc.size -= size
        if parent is not None:
            parent.size -= size
            before = len(parent.dirs) + len(parent.files)
            parent.dirs = [d for d in parent.dirs if d.name != name]
            parent.files = [f for f in parent.files if f[0] != name]
            if len(parent.dirs) + len(parent.files) == before:
                parent.other_size = max(0, parent.other_size - size)
        for p in list(self.candidates):
            if p == path or p.startswith(path + os.sep):
                del self.candidates[p]


def node_json(node, flagged=frozenset()):
    """flagged: paths that are cleanup suggestions, so the UI can colour them."""
    items = [{"name": d.name, "path": d.path, "size": d.size, "isDir": True, "files": d.nfiles,
              "cache": d.path in flagged} for d in node.dirs]
    items += [{"name": n, "path": os.path.join(node.path, n), "size": s, "isDir": False,
               "cache": os.path.join(node.path, n) in flagged} for n, s in node.files]
    items.sort(key=lambda i: i["size"], reverse=True)
    return {"path": node.path, "name": node.name, "size": node.size, "files": node.nfiles,
            "items": items, "otherSize": node.other_size, "otherCount": node.other_count}


def largest_files(tree, limit=300):
    out = []
    stack = [tree]
    while stack:
        n = stack.pop()
        out.extend((s, os.path.join(n.path, name)) for name, s in n.files)
        stack.extend(n.dirs)
    out.sort(reverse=True)
    return [{"path": p, "name": os.path.basename(p), "size": s} for s, p in out[:limit]]


